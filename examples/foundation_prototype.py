import os
import requests
from bs4 import BeautifulSoup
from groq import Groq

# 1. Hardcode a cybersecurity blog URL for testing
TEST_URL = "https://www.microsoft.com/en-us/security/blog/2023/10/18/multiple-north-korean-threat-actors-exploiting-the-teamcity-cve-2023-42793-vulnerability/"

# 2. Set up the Groq client
# This automatically looks for the GROQ_API_KEY environment variable on your computer
client = Groq()

def fetch_and_clean_webpage(url):
    print(f"Fetching URL: {url}")
    # Send an HTTP GET request to the website to download the HTML
    response = requests.get(url)
    
    # Check if the website blocked us or if the link is broken
    if response.status_code != 200:
        print(f"Failed to fetch webpage. Status code: {response.status_code}")
        return None
        
    print("Webpage fetched successfully. Cleaning HTML tags...")
    
    # Parse the HTML content using BeautifulSoup
    soup = BeautifulSoup(response.text, 'html.parser')
    
    # Extract raw text, throwing away all HTML tags, scripts, and styling
    # separator=' ' puts a space between different paragraphs instead of mashing them together
    # strip=True cleans up extra empty spaces
    clean_text = soup.get_text(separator=' ', strip=True)
    
    # Return the first 50000 characters just to make sure we don't send too much data
    return clean_text[:50000]

def generate_kql_with_groq(clean_text):
    print("Sending text to Groq API (model: llama3-70b-8192)...")
    print("Waiting for response... (this usually takes 5-10 seconds)\n")
    
    # This is the exact instruction you wanted to give to the AI
    prompt = f"""
    Extract the top 3 attacker behaviors from this threat report and 
    write one KQL detection query for each behavior using 
    DeviceProcessEvents table.
    
    Threat Report:
    {clean_text}
    """
    
    # Send the request to the Groq API
    chat_completion = client.chat.completions.create(
        messages=[
            {
                "role": "user",
                "content": prompt,
            }
        ],
        model="llama3-70b-8192",
    )
    
    # Return the text generated by the AI
    return chat_completion.choices[0].message.content

# This tells Python where to start running the code
if __name__ == "__main__":
    # Step 1 & 2: Fetch and clean the text from our test URL
    article_text = fetch_and_clean_webpage(TEST_URL)
    
    # If we successfully got text back, move to the next step
    if article_text:
        # Step 3: Send the cleaned text to Groq to get KQL queries
        kql_result = generate_kql_with_groq(article_text)
        
        # Step 4: Print the final result to the terminal
        print("="*60)
        print(" GROQ AI RESPONSE (ATTACK BEHAVIORS & KQL QUERIES):")
        print("="*60 + "\n")
        print(kql_result)
